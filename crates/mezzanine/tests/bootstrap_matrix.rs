//! Assembled production installer qualification, not vendor runtime acceptance.
//! Every root and payload is fixture-owned; no vendor/provider is invoked.

use std::os::unix::fs::{MetadataExt, PermissionsExt};
use std::path::{Path, PathBuf};

/// Captures names, inode/mode/time and file bytes, excluding access time changed
/// by observation itself. New locks/journals/roots or content writes are visible.
type Observation = (PathBuf, u64, u32, i64, i64, Option<Vec<u8>>);

/// Returns bounded fixture observations for exact read-only comparisons.
fn snapshot(root: &Path) -> Vec<Observation> {
    fn walk(root: &Path, path: &Path, rows: &mut Vec<Observation>) {
        let metadata = std::fs::symlink_metadata(path).unwrap();
        assert!(!metadata.file_type().is_symlink());
        rows.push((
            path.strip_prefix(root).unwrap().into(),
            metadata.ino(),
            metadata.mode(),
            metadata.mtime(),
            metadata.mtime_nsec(),
            metadata.is_file().then(|| std::fs::read(path).unwrap()),
        ));
        if metadata.is_dir() {
            let mut children = std::fs::read_dir(path)
                .unwrap()
                .map(|entry| entry.unwrap().path())
                .collect::<Vec<_>>();
            children.sort();
            for child in children {
                walk(root, &child, rows);
            }
        }
    }
    let mut rows = Vec::new();
    walk(root, root, &mut rows);
    rows
}

/// The actual executable must upgrade every shipped JSONC-era loader layout,
/// including a genuinely new higher-priority authored JSONC file. Historical
/// fixture bytes use independently frozen source and the helper reference already
/// generated by this same binary; no runtime receipt-selected authority or vendor
/// execution is introduced. Assert installed registration and receipt identity,
/// exact preview nonmutation, repeat stability and authored-data conservation.
#[test]
fn bootstrap_binary_upgrades_historical_opencode_layouts() {
    let member = serde_json::json!("./plugins/mezzanine/opencode_tui.mjs");
    for revision in [7, 8, 9] {
        for (name, pointer) in [
            ("tui.json", "/plugin"),
            ("tui.json", "/tui/plugin"),
            ("tui.jsonc", "/plugin"),
            ("tui.jsonc", "/tui/plugin"),
        ] {
            let home = std::env::temp_dir().join(format!(
                "mez-bootstrap-layout-{revision}-{}-{}",
                std::process::id(),
                rand::random::<u64>()
            ));
            std::fs::create_dir(&home).unwrap();
            std::fs::set_permissions(&home, std::fs::Permissions::from_mode(0o700)).unwrap();
            let vendor = home.join(".config/opencode");
            std::fs::create_dir_all(&vendor).unwrap();
            let authored = if pointer == "/plugin" {
                serde_json::json!({"plugin":["user-root"],"tui":{"plugin":["user-nested"]},"theme":"authored"})
            } else {
                serde_json::json!({"tui":{"plugin":["user-nested"]},"theme":"authored"})
            };
            std::fs::write(vendor.join(name), serde_json::to_vec(&authored).unwrap()).unwrap();
            let invoke = |flags: &[&str]| {
                let output = std::process::Command::new(env!("CARGO_BIN_EXE_mez"))
                    .args(["--json", "bootstrap", "opencode"])
                    .args(flags)
                    .env_clear()
                    .env("HOME", &home)
                    .stdin(std::process::Stdio::null())
                    .output()
                    .unwrap();
                assert!(
                    output.status.success(),
                    "rev{revision}/{name}/{pointer}: {output:?}"
                );
                assert!(output.stderr.is_empty());
                serde_json::from_slice::<serde_json::Value>(&output.stdout).unwrap()
            };
            assert_eq!(invoke(&[])["result"], "installed");
            let receipt_path = snapshot(&home)
                .into_iter()
                .find(|row| {
                    row.0.file_name() == Some(std::ffi::OsStr::new("ownership-opencode.json"))
                })
                .map(|row| home.join(row.0))
                .unwrap();
            let mut receipt: serde_json::Value =
                serde_json::from_slice(&std::fs::read(&receipt_path).unwrap()).unwrap();
            let manifest = &mut receipt["manifest"];
            assert_eq!(manifest["revision"], 10);
            manifest["revision"] = revision.into();
            let entries = manifest["entries"].as_array_mut().unwrap();
            if revision == 7 {
                entries.retain(|entry| entry["path"] != "plugins/mezzanine/request_accounting.mjs");
                std::fs::remove_file(vendor.join("plugins/mezzanine/request_accounting.mjs"))
                    .unwrap();
            }
            for entry in entries {
                let path = entry["path"].as_str().unwrap().to_owned();
                let frozen = match path.as_str() {
                    "plugins/mezzanine/persistent_client.mjs" => Some(if revision == 7 {
                        include_bytes!(
                            "../src/integrations/bootstrap/history/persistent_client_v5.mjs"
                        )
                        .as_slice()
                    } else {
                        include_bytes!(
                            "../src/integrations/bootstrap/history/persistent_client_v6.mjs"
                        )
                        .as_slice()
                    }),
                    "plugins/mezzanine/request_accounting.mjs" if revision == 8 => Some(
                        include_bytes!(
                            "../src/integrations/bootstrap/history/request_accounting_v8.mjs"
                        )
                        .as_slice(),
                    ),
                    _ => None,
                };
                if let Some(bytes) = frozen {
                    entry["artifact"] = serde_json::json!({"File":{"bytes":bytes}});
                    std::fs::write(vendor.join(path), bytes).unwrap();
                }
            }
            std::fs::write(&receipt_path, serde_json::to_vec(&receipt).unwrap()).unwrap();
            // A JSONC file appearing after a JSON installation really changes
            // loader selection; the nested higher-priority member must be used.
            let higher = serde_json::json!({"tui":{"plugin":["higher-user"]},"theme":"higher"});
            let (effective_name, effective_pointer) = if name == "tui.json" {
                std::fs::write(
                    vendor.join("tui.jsonc"),
                    serde_json::to_vec(&higher).unwrap(),
                )
                .unwrap();
                ("tui.jsonc", "/tui/plugin")
            } else {
                (name, pointer)
            };
            let before = snapshot(&home);
            assert_eq!(invoke(&["--dry-run"])["result"], "preview");
            assert_eq!(snapshot(&home), before);
            assert_eq!(invoke(&["--check"])["result"], "checked");
            assert_eq!(snapshot(&home), before);
            let upgraded = invoke(&[]);
            assert_eq!(upgraded["result"], "upgraded");
            assert_eq!(upgraded["manifest_revision"], 10);
            assert_eq!(upgraded["runtime_verification"], "not-performed");
            let current: serde_json::Value =
                serde_json::from_slice(&std::fs::read(&receipt_path).unwrap()).unwrap();
            assert_eq!(current["manifest"]["revision"], 10);
            let registration = current["manifest"]["entries"]
                .as_array()
                .unwrap()
                .iter()
                .find(|entry| entry["artifact"].get("JsoncArrayEntry").is_some())
                .unwrap();
            assert_eq!(registration["path"], effective_name);
            assert_eq!(
                registration["artifact"]["JsoncArrayEntry"]["pointer"],
                effective_pointer
            );
            let actual: serde_json::Value =
                serde_json::from_slice(&std::fs::read(vendor.join(effective_name)).unwrap())
                    .unwrap();
            assert_eq!(
                actual
                    .pointer(effective_pointer)
                    .unwrap()
                    .as_array()
                    .unwrap()
                    .iter()
                    .filter(|value| **value == member)
                    .count(),
                1
            );
            if name == "tui.json" {
                let old: serde_json::Value =
                    serde_json::from_slice(&std::fs::read(vendor.join(name)).unwrap()).unwrap();
                assert_eq!(old, authored);
            }
            let settled = snapshot(&home);
            assert_eq!(invoke(&[])["result"], "unchanged");
            assert_eq!(snapshot(&home), settled);
            assert_eq!(invoke(&["--uninstall"])["result"], "uninstalled");
            let final_document: serde_json::Value =
                serde_json::from_slice(&std::fs::read(vendor.join(effective_name)).unwrap())
                    .unwrap();
            assert_eq!(
                final_document,
                if name == "tui.json" { higher } else { authored }
            );
            std::fs::remove_dir_all(home).unwrap();
        }
    }
}

/// Bare production bootstrap must discover each documented default root, keep
/// whole-tree preview/check observation-only, install once/repeat unchanged,
/// repair a missing owned file and preserve unrelated data. This composes actual
/// compiled recipes with publication; it does not prove loaded hooks, process
/// association, accounting, custom-root loader acceptance or macOS execution.
#[test]
fn bootstrap_six_default_roots_preview_repeat_and_missing_file_repair() {
    for (harness, suffix, owned) in [
        (
            "claude",
            ".claude",
            "skills/mezzanine-telemetry/hooks/register.mjs",
        ),
        ("codex", ".codex", "hooks.json"),
        ("copilot", ".copilot", "hooks/mezzanine.json"),
        ("opencode", ".config/opencode", "plugins/mezzanine.js"),
        ("cursor", ".cursor", "hooks.json"),
        ("pi", ".pi/agent", "extensions/mezzanine/package.json"),
    ] {
        let home = std::env::temp_dir().join(format!(
            "mez-bootstrap-six-{harness}-{}-{}",
            std::process::id(),
            rand::random::<u64>()
        ));
        std::fs::create_dir(&home).unwrap();
        std::fs::set_permissions(&home, std::fs::Permissions::from_mode(0o700)).unwrap();
        std::fs::write(home.join("unrelated.txt"), b"UNCHANGED USER DATA").unwrap();
        let vendor = home.join(suffix);
        let invoke = |flags: &[&str]| {
            let output = std::process::Command::new(env!("CARGO_BIN_EXE_mez"))
                .args(["--json", "bootstrap", harness])
                .args(flags)
                .env_clear()
                .env("HOME", &home)
                .stdin(std::process::Stdio::null())
                .output()
                .unwrap();
            assert!(output.status.success(), "{harness}: {output:?}");
            assert!(output.stderr.is_empty());
            serde_json::from_slice::<serde_json::Value>(&output.stdout).unwrap()
        };
        let before = snapshot(&home);
        let preview = invoke(&["--dry-run"]);
        assert_eq!(preview["result"], "preview");
        assert_eq!(preview["scope_root"], vendor.to_str().unwrap());
        assert_eq!(snapshot(&home), before, "{harness} absent preview wrote");
        let installed = invoke(&[]);
        assert_eq!(installed["result"], "installed");
        assert_eq!(installed["runtime_verification"], "not-performed");
        assert_eq!(invoke(&[])["result"], "unchanged");
        std::fs::write(
            vendor.join("unrelated.json"),
            b"PRIVATE AUTHORED VENDOR DATA",
        )
        .unwrap();
        let before = snapshot(&home);
        assert_eq!(invoke(&["--check"])["result"], "checked");
        assert_eq!(snapshot(&home), before, "{harness} check wrote");
        assert_eq!(invoke(&["--dry-run"])["result"], "preview");
        assert_eq!(snapshot(&home), before, "{harness} installed preview wrote");
        assert_eq!(invoke(&["--uninstall", "--dry-run"])["result"], "preview");
        assert_eq!(snapshot(&home), before, "{harness} uninstall preview wrote");
        let owned = vendor.join(owned);
        let original = std::fs::read(&owned).unwrap();
        std::fs::remove_file(&owned).unwrap();
        assert_eq!(invoke(&[])["result"], "repaired");
        assert_eq!(std::fs::read(&owned).unwrap(), original);
        assert_eq!(
            std::fs::read(vendor.join("unrelated.json")).unwrap(),
            b"PRIVATE AUTHORED VENDOR DATA"
        );
        assert_eq!(
            std::fs::read(home.join("unrelated.txt")).unwrap(),
            b"UNCHANGED USER DATA"
        );
        std::fs::remove_dir_all(home).unwrap();
    }
}
