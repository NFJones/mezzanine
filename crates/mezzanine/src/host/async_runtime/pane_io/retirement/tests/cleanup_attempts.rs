//! Public automatic drain factories retain creation-time attempt authority.
//!
//! These are real native roots with held PTYs. Old unpolled/suspended futures
//! must fail before effects after a new explicit epoch or source. Fresh child
//! replies precede independent authorized cleanup and exact native wait/SRCH.

use super::*;
use std::os::fd::OwnedFd;

/// Sends only a bounded fixture protocol through its owned nonblocking master.
async fn input(master: &OwnedFd, mut bytes: &[u8]) -> bool {
    let deadline = Instant::now() + Duration::from_millis(500);
    while !bytes.is_empty() && Instant::now() < deadline {
        match rustix::io::write(master, bytes) {
            Ok(0) => return false,
            Ok(count) => bytes = &bytes[count..],
            Err(rustix::io::Errno::AGAIN | rustix::io::Errno::INTR) => {}
            Err(_) => return false,
        }
        if !bytes.is_empty() {
            sleep(Duration::from_millis(5)).await;
        }
    }
    bytes.is_empty()
}

/// Requires child-generated bytes, never terminal echo, within a fixture bound.
async fn marker(master: &OwnedFd, expected: &str) -> bool {
    let deadline = Instant::now() + Duration::from_millis(500);
    let mut output = Vec::new();
    while Instant::now() < deadline && output.len() < 64 * 1024 {
        let mut bytes = [0u8; 4096];
        match rustix::io::read(master, &mut bytes) {
            Ok(0) => break,
            Ok(count) => output.extend_from_slice(&bytes[..count]),
            Err(rustix::io::Errno::AGAIN | rustix::io::Errno::INTR) => {}
            Err(_) => break,
        }
        if String::from_utf8_lossy(&output).contains(expected) {
            return true;
        }
        sleep(Duration::from_millis(5)).await;
    }
    false
}

/// Starts an exclusively owned signal-resistant reply root before any intent.
async fn reply_process(
    owner: &PaneProcessRetirementOwner,
) -> (mez_mux::process::PaneProcess, OwnedFd, rustix::process::Pid) {
    let process = mez_mux::process::spawn_retained_argv_pty_process(std::path::Path::new("/bin/sh"),
        &["-c".into(), "trap '' HUP TERM; stty -echo; printf 'scope-ready\\n'; while IFS= read -r line; do if [ \"$line\" = fixture-finish ]; then exit 0; fi; printf 'scope-child:%s\\n' \"$line\"; done".into()],
        &[], mez_mux::layout::Size::new(80, 24).unwrap(), None, owner.reserve().unwrap()).unwrap();
    let pid =
        rustix::process::Pid::from_raw(i32::try_from(process.primary_pid()).unwrap()).unwrap();
    let master = process.duplicate_master_fd().unwrap();
    assert!(marker(&master, "scope-ready").await);
    (process, master, pid)
}

/// Both never-polled and already-suspended automatic futures keep their old
/// token. The suspended case issued only genuine in-budget HUP before holding
/// the same operation; new retry must not cause that old future to adopt it.
#[tokio::test(flavor = "current_thread")]
async fn automatic_drain_cannot_adopt_retry_after_unpolled_or_suspended_scope() {
    for suspended in [false, true] {
        let owner = PaneProcessRetirementOwner::default();
        let (mut process, master, pid) = reply_process(&owner).await;
        let original = process.begin_native_termination(!suspended).unwrap();
        drop(process);
        owner.seal();
        let old = drain_native_pane_retirement(
            &owner,
            Instant::from_std(original) + Duration::from_secs(1),
        );
        tokio::pin!(old);
        if suspended {
            assert!(
                futures_util::poll!(&mut old).is_pending(),
                "initial graceful operation did not remain gated"
            );
        }
        tokio::time::sleep_until(Instant::from_std(original) + Duration::from_millis(10)).await;
        let token = owner
            .prepare_explicit_cleanup_retry((Instant::now() + Duration::from_secs(1)).into_std())
            .unwrap()
            .admit()
            .unwrap();
        let old_result = old.await;
        let pending_before_cleanup = owner.outstanding() == 1;
        let live = rustix::process::test_kill_process(pid) == Ok(());
        let replied = input(&master, b"old-scope-probe\n").await
            && marker(&master, "scope-child:old-scope-probe").await;
        let cleanup = drain_native_pane_retirement_for_attempt(
            &owner,
            &token,
            Instant::from_std(token.deadline()),
        )
        .await;
        let absent = rustix::process::test_kill_process(pid) == Err(rustix::io::Errno::SRCH);
        drop(master);
        assert!(
            cleanup.is_ok() && absent && owner.outstanding() == 0,
            "independent authorized native cleanup failed: {cleanup:?}"
        );
        assert!(old_result.unwrap_err().message().contains("stale"));
        assert!(
            pending_before_cleanup && live && replied,
            "old automatic future affected original root before authorized cleanup"
        );
    }
}

/// A preallocated owner with no admission yet may bind its FIRST initial source
/// without changing the creation budget. This is not permission to bind a
/// completed/reused source or any explicit retry epoch.
#[tokio::test(flavor = "current_thread")]
async fn preallocated_owner_scope_binds_only_first_initial_source() {
    let owner = PaneProcessRetirementOwner::default();
    let early = drain_native_pane_retirement(&owner, Instant::now() + Duration::from_secs(1));
    let (process, master, pid) = reply_process(&owner).await;
    drop(process);
    let result = early.await;
    let absent = rustix::process::test_kill_process(pid) == Err(rustix::io::Errno::SRCH);
    drop(master);
    assert!(
        result.is_ok() && absent && owner.outstanding() == 0,
        "first admitted source did not settle under captured budget: {result:?}"
    );
}

/// An unpolled automatic scope from a completed source must not attach to the
/// same owner's new source after native zero. Require a fresh root response
/// before its independent initial cleanup, not an explicit epoch mint.
#[tokio::test(flavor = "current_thread")]
async fn unpolled_automatic_scope_cannot_attach_to_idle_reused_owner() {
    let owner = PaneProcessRetirementOwner::default();
    let (a, master_a, pid_a) = reply_process(&owner).await;
    drop(a);
    let old = drain_native_pane_retirement(&owner, Instant::now() + Duration::from_secs(2));
    drain_native_pane_retirement(&owner, Instant::now() + Duration::from_secs(1))
        .await
        .unwrap();
    assert_eq!(
        rustix::process::test_kill_process(pid_a),
        Err(rustix::io::Errno::SRCH)
    );
    let (b, master_b, pid_b) = reply_process(&owner).await;
    drop(b);
    let old_result = old.await;
    let live = rustix::process::test_kill_process(pid_b) == Ok(());
    let replied = input(&master_b, b"fresh-source-probe\n").await
        && marker(&master_b, "scope-child:fresh-source-probe").await;
    let cleanup =
        drain_native_pane_retirement(&owner, Instant::now() + Duration::from_secs(1)).await;
    let absent = rustix::process::test_kill_process(pid_b) == Err(rustix::io::Errno::SRCH);
    drop((master_a, master_b));
    assert!(
        cleanup.is_ok() && absent && owner.outstanding() == 0,
        "new initial source failed native settlement"
    );
    assert!(old_result.unwrap_err().message().contains("stale") && live && replied);
}
